CONTACT_JS = os.path.join(ROOT, 'plugins', 'assets', 'layout_contact.js')


# ---------------------------------------------------------------------------
# Pages of a corpus
# ---------------------------------------------------------------------------

def deck_pages(deck_dir):
    """Pages of a slide project: [{deck, chapter, dir, html, source}] in deck order."""
    deck = os.path.basename(os.path.normpath(deck_dir))
    site = os.path.join(deck_dir, '_site')
    pages = []
    for chapter in sorted(os.listdir(site)):
        structure = os.path.join(site, chapter, 'html', 'structure', 'structure.yaml')
        if not os.path.isfile(structure):
            continue
        with open(structure) as fid:
            entries = yaml.safe_load(fid) or []
        for e in entries:
            html = os.path.join(site, chapter, 'html', e['dir'] + e['filename'])
            if os.path.isfile(html):
                pages.append({'deck': deck, 'chapter': chapter, 'dir': e['dir'].rstrip('/'),
                              'html': os.path.abspath(html),
                              'source': os.path.abspath(os.path.join(deck_dir, 'src', chapter,
                                                                     e['dir'] + e['filename'] + '.j2'))})
    return pages


def page_key(page):
    return '/'.join(x for x in (page['deck'], page['chapter'], page['dir']) if x)


# ---------------------------------------------------------------------------
# Measurement (cached)
# ---------------------------------------------------------------------------

def measure(pages, output_dir, jobs=3, force=False, log=print):
    """Measure the pages not measured since they were generated, with `jobs`
    browsers in parallel. Sets page['out'] and page['layout_path']."""
    todo = []
    for p in pages:
        p['out'] = os.path.abspath(os.path.join(output_dir, 'pages', page_key(p)))
        p['layout_path'] = os.path.join(p['out'], 'layout.json')
        if force or not os.path.isfile(p['layout_path']) \
                or os.path.getmtime(p['layout_path']) < os.path.getmtime(p['html']):
            todo.append(p)
    log(f'{len(pages)} pages, {len(todo)} to measure')
    if not todo:
        return
    chunks = [todo[i::jobs] for i in range(jobs) if todo[i::jobs]]
    procs, files = [], []
    for chunk in chunks:
        with tempfile.NamedTemporaryFile('w', suffix='.json', delete=False) as fid:
            json.dump([{'html': p['html'], 'out': p['out']} for p in chunk], fid)
        files.append(fid.name)
        procs.append(subprocess.Popen(['node', MEASURE_JS, f'--input={fid.name}', '--images=render'],
                                      stderr=subprocess.PIPE, text=True))
    for proc, name in zip(procs, files):
        _, err = proc.communicate()
        os.remove(name)
        for line in err.splitlines():
            if line.startswith('layout_measure:'):
                log(line)


