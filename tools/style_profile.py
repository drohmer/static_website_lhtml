def _box_distance(a, b, scale):
    if a is None or b is None:
        return 0 if a is b else 1
    return sum(abs(x - y) for x, y in zip(a, b)) / (4 * scale)


def _median_box(boxes):
    boxes = [b for b in boxes if b]
    return tuple(round(lr._median([b[i] for b in boxes])) for i in range(4)) if boxes else None


def type_profile(slides, area_w):
    """Typical measures of the slides of a type, and its examples: the
    slides closest to the typical measures, without layout problems."""
    f = [s['features'] for s in slides]
    med = lambda k: lr._median([x[k] for x in f])
    typical = {'words': med('words'), 'formulas': med('formulas'), 'code_lines': med('code_lines'),
               'media_items': med('media_items'),
               'text_box': _median_box([x['text_box'] for x in f]),
               'code_box': _median_box([x['code_box'] for x in f]),
               'media_box': _median_box([x['media_box'] for x in f]),
               'fixed_media': round(sum(x['fixed_media'] for x in f) / max(sum(x['media_items'] for x in f), 1), 2)}

    def distance(s):
        x = s['features']
        return (sum(_box_distance(x[k], typical[k], area_w) for k in ('text_box', 'code_box', 'media_box'))
                + abs(x['words'] - typical['words']) / max(typical['words'], 10))

    clean = [s for s in slides if lr.count_problems(s['analysis']) == 0]
    ranked = sorted(clean or slides, key=lambda s: (lr.count_warnings(s['analysis']), distance(s)))
    # examples from different decks first
    examples, seen = [], set()
    for s in ranked:
        if s['page']['deck'] not in seen:
            examples.append(s)
            seen.add(s['page']['deck'])
    examples += [s for s in ranked if s not in examples]
    return typical, examples


def _box_text(box):
    return f'x {box[0]}..{box[2]}, y {box[1]}..{box[3]}' if box else '-'


def _source_excerpt(path, max_lines=40):
    try:
        with open(path, encoding='utf-8', errors='replace') as fid:
            lines = fid.read().strip('\n').splitlines()
    except OSError:
        return '(source not found)'
    if len(lines) > max_lines:
        lines = lines[:max_lines] + [f'... ({len(lines) - max_lines} more lines)']
    return '\n'.join(lines)


def _top(counter, n, fmt=lambda k, v: f'`{k}` ({v})'):
    return ', '.join(fmt(k, v) for k, v in counter.most_common(n))


def style_markdown(decks, slides, types, idioms, n_examples=3):
    total = len(slides)
    lines = ['# Style profile', '',
             f"Measured on {total} slides of {len(decks)} decks: "
             + ', '.join(f"{d} ({n} slides)" for d, n in decks.items()) + '.', '',
             'Coordinates in CSS px on a 1920×1080 slide, origin at the top-left corner.', '',
             'To write a new slide in this style: choose its layout type below, start from the '
             'source of the closest example, keep the usual title, columns, font sizes and density '
             'of the deck, then check it with `generate.py -l --layout`.', '',
             '## Usual values of each deck', '']
    for deck, norms in decks_norms_items(slides):
        lines += [f'### {deck}', '', lr.norms_markdown(norms).split('\n', 2)[2].strip(), '']

    lines += ['## Layout types', '',
              '| type | slides | ' + ' | '.join(decks) + ' | words | description |',
              '|------|--------|' + '|'.join('---' for _ in decks) + '|-------|-------------|']
    for name, t in types.items():
        per_deck = Counter(s['page']['deck'] for s in t['slides'])
        lines.append(f"| {name} | {len(t['slides'])} ({round(100 * len(t['slides']) / total)} %) | "
                     + ' | '.join(str(per_deck.get(d, 0)) for d in decks)
                     + f" | {t['typical']['words']} | {TYPES[name]} |")
    lines.append('')
    for name, t in types.items():
        typ = t['typical']
        lines += [f'### {name}: {TYPES[name]}', '',
                  f"{len(t['slides'])} slides. Typical: {typ['words']} words, {typ['formulas']} formulas, "
                  f"{typ['code_lines']} lines of code, {typ['media_items']} figures "
                  f"({round(100 * typ['fixed_media'])} % of figures placed with position fixed/absolute).",
                  f"Text {_box_text(typ['text_box'])}; code {_box_text(typ['code_box'])}; "
                  f"figures {_box_text(typ['media_box'])}.", '',
                  f"Thumbnails of examples: `types/{name}.png`", '']
        for s in t['examples'][:n_examples]:
            lines += [f"Example `{page_key(s['page'])}` (source `{s['page']['source']}`):", '',
                      '```', _source_excerpt(s['page']['source']), '```', '']

    lines += ['## LHTML idioms (sources)', '',
              f"{idioms['files']} source files, {idioms['lines_per_slide']} non-empty lines per slide (median); "
              f"{idioms['inline_math']} inline formulas `\\( \\)`, {idioms['display_math']} display formulas.", '',
              '- Block tags: ' + _top(idioms['tags'], 12),
              '- Line starts (titles, lists): ' + _top(idioms['line_starts'], 8),
              '- Spacers `div::[height:...]::`: ' + _top(idioms['spacers'], 10),
              '- Style properties: ' + _top(idioms['properties'], 25),
              '- Classes: ' + (_top(idioms['classes'], 10) or 'none'), '',
              'Most used values of the main properties:', '']
    for prop, _ in idioms['properties'].most_common(14):
        values = Counter({v: n for (k, v), n in idioms['values'].items() if k == prop})
        lines.append(f'- `{prop}`: ' + _top(values, 8, lambda k, v: f'`{k}` ({v})'))
    lines += ['', 'Most frequent block openers (lines starting with `tag::` or `::`):', '']
    lines += [f'- `{k}` ({v})' for k, v in idioms['openers'].most_common(30)]
    return '\n'.join(lines) + '\n'


def decks_norms_items(slides):
    by_deck = {}
    for s in slides:
        by_deck.setdefault(s['page']['deck'], []).append(s)
    return [(deck, items[0]['norms']) for deck, items in by_deck.items()]


def write_type_sheets(output_dir, types, n=16):
    os.makedirs(os.path.join(output_dir, 'types'), exist_ok=True)
    sheets = []
    for name, t in types.items():
        rows = [(page_key(s['page']), os.path.relpath(s['page']['out'], os.path.join(output_dir, 'types')),
                 s['analysis']) for s in t['examples'][:n]]
        html = lr.contact_sheets_html(rows, {'w': 1920, 'h': 1080}, columns=4, rows_per_sheet=4)[0]
        path = os.path.abspath(os.path.join(output_dir, 'types', name + '.html'))
        with open(path, 'w', encoding='utf-8') as fid:
            fid.write(html)
        sheets.append({'html': path, 'png': path[:-len('.html')] + '.png'})
    with tempfile.NamedTemporaryFile('w', suffix='.json', delete=False) as fid:
        json.dump(sheets, fid)
    subprocess.run(['node', CONTACT_JS, f'--input={fid.name}'])
    os.remove(fid.name)


def profile(deck_dirs, output_dir, jobs=3, force=False, log=print):
    pages = [p for d in deck_dirs for p in deck_pages(d)]
    measure(pages, output_dir, jobs, force, log)
    by_deck = {}
    for p in pages:
        if os.path.isfile(p['layout_path']):
            with open(p['layout_path'], encoding='utf-8') as fid:
                by_deck.setdefault(p['deck'], []).append((p, json.load(fid)))
    slides, seen, duplicates = [], set(), 0
    for deck, items in by_deck.items():
        norms = lr.deck_norms([layout for _, layout in items])
        for p, layout in items:
            # a slide copied in several chapters counts once
            try:
                with open(p['source'], 'rb') as fid:
                    digest = hashlib.sha1(fid.read()).hexdigest()
            except OSError:
                digest = p['html']
            if digest in seen:
                duplicates += 1
                continue
            seen.add(digest)
            analysis = lr.analyse(layout, norms=norms)
            slides.append({'page': p, 'norms': norms, 'analysis': analysis,
                           'features': slide_features(layout)})
            slides[-1]['type'] = classify(slides[-1]['features'], layout['area'])
    types = {}
    for name in TYPES:
        members = [s for s in slides if s['type'] == name]
        if members:
            typical, examples = type_profile(members, 1920)
            types[name] = {'slides': members, 'typical': typical, 'examples': examples}
    idioms = source_idioms([s['page']['source'] for s in slides])
    decks = dict(Counter(s['page']['deck'] for s in slides))

    os.makedirs(output_dir, exist_ok=True)
    with open(os.path.join(output_dir, 'style.md'), 'w', encoding='utf-8', errors='replace') as fid:
        fid.write(style_markdown(decks, slides, types, idioms))
    data = {'decks': {d: n for d, n in decks.items()},
            'norms': dict(decks_norms_items(slides)),
            'types': {name: {'description': TYPES[name], 'count': len(t['slides']), 'typical': t['typical'],
                             'examples': [page_key(s['page']) for s in t['examples'][:16]]}
                      for name, t in types.items()},
            'slides': [{'page': page_key(s['page']), 'source': s['page']['source'], 'type': s['type'],
                        'features': s['features']} for s in slides],
            'idioms': {k: (v.most_common(60) if isinstance(v, Counter) else v) for k, v in idioms.items()
                       if k != 'values'}}
    with open(os.path.join(output_dir, 'style.json'), 'w') as fid:
        json.dump(data, fid, indent=1, ensure_ascii=False)
    write_type_sheets(output_dir, types)
    log(f"Style profile of {len(slides)} slides ({duplicates} duplicates ignored) -> "
        f"{os.path.join(output_dir, 'style.md')}")
    return types


def main():
    parser = argparse.ArgumentParser(description='Style profile of a corpus of slide decks.')
    parser.add_argument('decks', nargs='+', help='slide projects (with src/ and _site/)')
    parser.add_argument('-o', '--output', default='style/', help='output directory (default: style/)')
    parser.add_argument('-j', '--jobs', type=int, default=3, help='browsers in parallel (default: 3)')
    parser.add_argument('-f', '--force', action='store_true', help='measure again all the pages')
    args = parser.parse_args()
    profile(args.decks, args.output, args.jobs, args.force)


if __name__ == '__main__':
    main()
