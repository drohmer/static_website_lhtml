# Layout types
# ---------------------------------------------------------------------------

TYPES = {
    'section': 'section or title slide: no page title, a few words in large type',
    'media': 'page title + large figure(s) or video, almost no text',
    'media_row': 'page title + a row of 3 or more figures, little text',
    'columns': '2 or more columns of the same kind side by side (e.g. comparison: figure + caption in each)',
    'text_left_media_right': 'text on the left, figure(s) on the right',
    'media_left_text_right': 'figure(s) on the left, text on the right',
    'text_then_media': 'text, then figure(s) below',
    'media_then_text': 'figure(s), then text below',
    'text_code': 'text and code',
    'code_media': 'code and figure(s)',
    'code': 'mostly code',
    'text': 'text only (lists, formulas)',
    'other': 'none of the above',
}


def _union(rects):
    if not rects:
        return None
    return (min(r[0] for r in rects), min(r[1] for r in rects), max(r[2] for r in rects), max(r[3] for r in rects))


def _surface(rects):
    return sum((r[2] - r[0]) * (r[3] - r[1]) for r in rects)


def slide_features(layout):
    """Content of a slide (page title excluded) as text, code and media
    regions: their bounding boxes, the fraction of the area they cover, and
    counts (words, formulas, lines of code, media items)."""
    blocks = lr._visible(layout['blocks'])
    area = layout['area']
    surface = max(area['w'] * area['h'], 1)
    title = lr.page_title(blocks)
    content = blocks[1:] if title else blocks
    text, code, media = [], [], []
    media_items, fixed_media, fonts = [], 0, []
    for b in content:
        stats = b.get('text') or {}
        is_code = b['kind'] == 'code' or stats.get('code_lines', 0) > 0 and not stats.get('words')
        parts = lr._align_parts(b)
        for r in parts:
            if r[4] in ('media', 'trimmed'):
                media.append(r[:4])
            elif is_code:
                code.append(r[:4])
            elif r[4] == 'text':
                text.append(r[:4])
        boxes = [r[:4] for r in parts if r[4] in ('media', 'trimmed')]
        media_items += boxes
        if boxes and b.get('position') in ('fixed', 'absolute'):
            fixed_media += len(boxes)
        if stats.get('words'):
            fonts.append(b['font_size'])
    d = lr.density(content, area)
    return {
        'title': lr._tag(title) + f" {title['font_size']}px" if title else None,
        'words': d['words'], 'formulas': d['formulas'], 'code_lines': d['code_lines'], 'items': d['items'],
        'max_font': max(fonts) if fonts else None,
        'text_box': _union(text), 'code_box': _union(code), 'media_box': _union(media),
        'text_area': round(_surface(text) / surface, 3), 'code_area': round(_surface(code) / surface, 3),
        'media_area': round(_surface(media) / surface, 3),
        'media_items': len(media_items), 'fixed_media': fixed_media,
        'media_row': _row_size(media_items),
        'bands': _bands(text, code, media, area),
    }


def _bands(text, code, media, area, min_gap=40):
    """Columns of the content: the content is projected on the x axis
    (ignoring lines wider than half the area, such as a sentence above
    columns) and cut at the empty gaps of at least min_gap px. Returns, for
    each column, its x range and its dominant content: 'text', 'media' or
    'mixed' (both, e.g. a figure and its caption)."""
    typed = [(r, 'text') for r in text + code] + [(r, 'media') for r in media]
    typed = [(r, t) for r, t in typed if r[2] - r[0] <= 0.5 * area['w']]
    if not typed:
        return []
    intervals = sorted((r[0], r[2]) for r, _ in typed)
    bands = [list(intervals[0])]
    for x0, x1 in intervals[1:]:
        if x0 - bands[-1][1] < min_gap:
            bands[-1][1] = max(bands[-1][1], x1)
        else:
            bands.append([x0, x1])
    result = []
    for x0, x1 in bands:
        inside = [(r, t) for r, t in typed if r[0] >= x0 and r[2] <= x1]
        t_area = _surface([r for r, t in inside if t == 'text'])
        m_area = _surface([r for r, t in inside if t == 'media'])
        if t_area + m_area < 0.003 * area['w'] * area['h']:
            continue        # a stray label
        kind = 'mixed' if min(t_area, m_area) > 0.15 * (t_area + m_area) else ('media' if m_area > t_area else 'text')
        result.append({'x0': x0, 'x1': x1, 'kind': kind})
    return result


def _row_size(boxes):
    """Largest number of boxes side by side on a same line."""
    best = 0
    for b in boxes:
        row = [c for c in boxes if min(b[3], c[3]) - max(b[1], c[1]) > 0.5 * min(b[3] - b[1], c[3] - c[1])]
        best = max(best, len(row))
    return best


def classify(f, area):
    """Layout type of a slide (see TYPES) from its features."""
    words, text_box, media_box = f['words'], f['text_box'], f['media_box']
    has_code = f['code_lines'] >= 3 or f['code_area'] > 0.03
    has_media = f['media_area'] > 0.02
    if f['title'] is None and words <= 25 and not has_code and (f['max_font'] or 0) >= 40:
        return 'section'
    if has_code:
        if has_media:
            return 'code_media'
        return 'text_code' if words > 15 else 'code'
    if not has_media:
        return 'text' if words else 'other'
    bands = f['bands']
    if len(bands) >= 2:
        kinds = [b['kind'] for b in bands]
        if len(set(kinds)) == 1 or kinds.count('mixed') >= 2:
            return 'media_row' if kinds[0] == 'media' and len(bands) >= 3 and words <= 40 else 'columns'
        if kinds[0] == 'text' and kinds[-1] in ('media', 'mixed'):
            return 'text_left_media_right'
        if kinds[0] in ('media', 'mixed') and kinds[-1] == 'text':
            return 'media_left_text_right'
    if f['media_row'] >= 3 and words <= 40:
        return 'media_row'
    if words <= 15 or text_box is None:
        return 'media'
    tcx, mcx = (text_box[0] + text_box[2]) / 2, (media_box[0] + media_box[2]) / 2
    overlap_y = min(text_box[3], media_box[3]) - max(text_box[1], media_box[1])
    side_by_side = overlap_y > 0.3 * min(text_box[3] - text_box[1], media_box[3] - media_box[1])
    if side_by_side and abs(mcx - tcx) > 0.2 * area['w']:
        return 'text_left_media_right' if mcx > tcx else 'media_left_text_right'
    return 'text_then_media' if (media_box[1] + media_box[3]) > (text_box[1] + text_box[3]) else 'media_then_text'


# ---------------------------------------------------------------------------
# Idioms of the LHTML sources
# ---------------------------------------------------------------------------

OPENER = re.compile(r'^\s*([a-zA-Z_][\w-]*)?::')
STYLE = re.compile(r'\[([^\[\]\n]*:[^\[\]\n]*)\]')
CODE_OPENER = re.compile(r'^code::\[[^\]]*\]\s*$')
SPACER = re.compile(r'^\s*(?:div)?::\[\s*height:\s*([^;\]]+);?\s*\]::\s*$')


def source_idioms(paths):
    """Frequencies of the constructs used in the LHTML sources."""
    openers, tags, props, values, spacers, starts, classes = (Counter() for _ in range(7))
    n_lines, inline_math, display_math = [], 0, 0
    for path in paths:
        try:
            with open(path, encoding='utf-8', errors='replace') as fid:
                source = fid.read()
        except OSError:
            continue
        lines = [l for l in source.splitlines() if l.strip()]
        n_lines.append(len(lines))
        inline_math += source.count('\\(')
        display_math += source.count('\\[') + source.count('$$')
        for m in re.finditer(r'\(\.([\w-]+)', source):
            classes[m.group(1)] += 1
        in_code = False
        for line in lines:
            s = line.strip()
            if in_code:     # content of a code block: not LHTML
                in_code = s != '::'
                continue
            if CODE_OPENER.match(s):
                in_code = True
            m = OPENER.match(s)
            if m:
                tags[m.group(1) or '(bare ::)'] += 1
                if s != '::':
                    openers[s] += 1
            sp = SPACER.match(s)
            if sp:
                spacers[sp.group(1).strip()] += 1
            for st in STYLE.finditer(s):
                for decl in st.group(1).split(';'):
                    if ':' in decl:
                        k, v = (x.strip() for x in decl.split(':', 1))
                        props[k] += 1
                        values[(k, v)] += 1
            head = re.match(r'^(=+|\*+)\s', s)
            if head:
                starts[head.group(1)] += 1
    return {'files': len(n_lines), 'lines_per_slide': lr._median(n_lines) if n_lines else None,
            'tags': tags, 'openers': openers, 'properties': props, 'values': values,
            'spacers': spacers, 'line_starts': starts, 'classes': classes,
            'inline_math': inline_math, 'display_math': display_math}


