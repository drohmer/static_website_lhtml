"""Style profile of a corpus of slide decks: what the slides of an author
usually look like, and how they are written.

    python tools/style_profile.py DECK [DECK ...] --output style/

DECK is the directory of a slide project generated by static_website_lhtml:
it contains src/<chapter>/ (LHTML sources) and _site/<chapter>/html/ (the
generated pages, with structure/structure.yaml). The generated pages are
measured as they are (nothing is regenerated), in headless Chrome
(plugins/assets/layout_measure.js, requires `npm install`). Measurements are
cached in <output>/pages/ and only redone for pages generated since.

Output, for an LLM writing new slides in the same style:

    style.md          usual values of each deck (title, columns, fonts,
                      density), layout types of the slides with their
                      frequency, typical measures and examples (source and
                      thumbnail), and the LHTML idioms used in the sources
    style.json        the same data, for scripts
    types/<type>.png  thumbnails of examples of each layout type
"""

